function openGuide(categoryId, serviceId) {
  const category = categories.find((item) => item.id === categoryId);
  const service = category?.services.find((item) => item.id === serviceId);
  if (!service) return;

  state.categoryId = categoryId;
  state.serviceId = serviceId;
  state.stepIndex = 0;

  if (!state.savedGuides.some((guide) => guide.id === serviceId)) {
    state.savedGuides.unshift({ id: serviceId, categoryId, label: getLocalizedValue(service.label) });
    state.savedGuides = state.savedGuides.slice(0, 6);
  }

  renderGuide();
  showScreen('guide');
  renderSavedGuides();
}

function renderGuide() {
  const category = categories.find((item) => item.id === state.categoryId);
  const service = category?.services.find((item) => item.id === state.serviceId);
  if (!category || !service) return;

  const step = service.steps[state.stepIndex];
  const totalSteps = service.steps.length;

  $('#step-badge').textContent = `${getText('stepLabel')} ${state.stepIndex + 1} ${getText('ofLabel')} ${totalSteps}`;
  $('#guide-category-tag').textContent = getLocalizedValue(category.label);
  $('#guide-title').textContent = `${category.icon} ${getLocalizedValue(service.label)}`;
  $('#guide-text').textContent = getLocalizedValue(step);
  $('#guide-image').src = service.image;
  $('#listen-btn').textContent = getText('listen');
  $('#stuck-btn').textContent = getText('stuck');
  $('#repeat-btn').textContent = getText('explainAgain');
  $('#prev-btn').textContent = getText('previous');
  $('#next-btn').textContent = state.stepIndex === totalSteps - 1 ? getText('done') : getText('next');
  $('.progress-label').textContent = getText('progress');
  $('#guide-back').textContent = getText('back');
  $('#category-back').textContent = getText('back');
  $('#modal-voice').textContent = getText('explainWithVoice');
  $('#modal-close').textContent = getText('gotIt');

  const progress = ((state.stepIndex + 1) / totalSteps) * 100;
  $('#progress-fill').style.width = `${progress}%`;

  const safetyMessage = $('#safety-message');
  if (service.safety) {
    safetyMessage.textContent = getText('safety');
    safetyMessage.classList.add('visible');
  } else {
    safetyMessage.textContent = '';
    safetyMessage.classList.remove('visible');
  }

  $('#prev-btn').disabled = state.stepIndex === 0;
  $('#next-btn').classList.toggle('primary', true);
}

function nextStep() {
  const category = categories.find((item) => item.id === state.categoryId);
  const service = category?.services.find((item) => item.id === state.serviceId);
  if (!service) return;

  if (state.stepIndex < service.steps.length - 1) {
    state.stepIndex += 1;
    renderGuide();
    return;
  }

  showScreen('dashboard');
  renderDashboard();
}

function prevStep() {
  if (state.stepIndex > 0) {
    state.stepIndex -= 1;
    renderGuide();
  }
}

let voiceLoadPromise = null;

function getVoiceForLanguage(lang, voices) {
  const preferred = {
    en: ['en-us', 'en-gb', 'en'],
    te: ['te-in', 'te'],
    hi: ['hi-in', 'hi']
  };
  const candidates = preferred[lang] || [lang];

  for (const candidate of candidates) {
    const match = voices.find((voice) => (voice.lang || '').toLowerCase().startsWith(candidate));
    if (match) return match;
  }

  return null;
}

function ensureVoicesLoaded() {
  if (!('speechSynthesis' in window)) return Promise.resolve([]);

  const synthesis = window.speechSynthesis;
  const voices = synthesis.getVoices();
  if (voices.length) return Promise.resolve(voices);
  if (voiceLoadPromise) return voiceLoadPromise;

  voiceLoadPromise = new Promise((resolve) => {
    let timeoutId;
    const finish = (waitForVoices) => {
      const availableVoices = synthesis.getVoices();
      if (waitForVoices && !availableVoices.length) return;
      synthesis.removeEventListener('voiceschanged', onVoicesChanged);
      window.clearTimeout(timeoutId);
      voiceLoadPromise = null;
      resolve(availableVoices);
    };
    const onVoicesChanged = () => finish(true);

    synthesis.addEventListener('voiceschanged', onVoicesChanged);
    timeoutId = window.setTimeout(() => finish(false), 1500);
  });

  return voiceLoadPromise;
}

async function speakText(text, lang = state.language) {
  if (!('speechSynthesis' in window) || !('SpeechSynthesisUtterance' in window)) {
    alert(getText('voiceUnavailable'));
    return;
  }

  const voices = await ensureVoicesLoaded();
  const bestVoice = getVoiceForLanguage(lang, voices);
  if (!bestVoice) {
    const voiceMessage = lang === 'te'
      ? getText('voiceNeedsTelugu')
      : lang === 'hi'
        ? getText('voiceNeedsHindi')
        : getText('voiceUnavailable');
    alert(voiceMessage);
    return;
  }

  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = { en: 'en-US', te: 'te-IN', hi: 'hi-IN' }[lang] || bestVoice.lang;
  utterance.voice = bestVoice;
  utterance.rate = 0.88;
  utterance.pitch = 1;
  utterance.onerror = (event) => {
    if (!['canceled', 'interrupted'].includes(event.error)) {
      alert(getText('voiceUnavailable'));
    }
  };

  window.speechSynthesis.cancel();
  window.speechSynthesis.speak(utterance);
}

