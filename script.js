function runSearch() {
  const query = $('#service-search')?.value.trim().toLowerCase() || '';
  const resultBox = $('#search-results');

  if (!resultBox) return;

  if (!query) {
    resultBox.innerHTML = '';
    return;
  }

  const hits = [];
  categories.forEach((category) => {
    const categoryText = getLocalizedValue(category.label).toLowerCase();
    if (categoryText.includes(query)) {
      hits.push({ type: 'category', label: getLocalizedValue(category.label), id: category.id });
    }

    category.services.forEach((service) => {
      const serviceText = getLocalizedValue(service.label).toLowerCase();
      if (serviceText.includes(query)) {
        hits.push({ type: 'service', label: getLocalizedValue(service.label), categoryId: category.id, serviceId: service.id });
      }
    });
  });

  if (!hits.length) {
    resultBox.innerHTML = `<p class="search-empty">${getText('noSearchMatch')}</p>`;
    return;
  }

  resultBox.innerHTML = hits.slice(0, 6).map((item) => `
    <button class="search-result-item" type="button" data-category="${item.categoryId || ''}" data-service="${item.serviceId || ''}">
      ${item.label}
    </button>
  `).join('');

  resultBox.querySelectorAll('.search-result-item').forEach((item) => {
    item.addEventListener('click', () => {
      if (item.dataset.service) {
        openGuide(item.dataset.category, item.dataset.service);
      } else if (item.dataset.category) {
        openCategory(item.dataset.category);
      }
    });
  });
}

